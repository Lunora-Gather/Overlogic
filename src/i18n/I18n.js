const ENTITY_ZH_TW = JSON.parse(toTraditional(JSON.stringify(ENTITY_ZH_CN)));

const DICTS = { en: EN, 'zh-CN': ZH_CN, 'zh-TW': ZH_TW };
const ENTITIES = { 'zh-CN': ENTITY_ZH_CN, 'zh-TW': ENTITY_ZH_TW };
let locale = 'en';

export function t(key, params = {}) {
  const template = DICTS[locale]?.[key] ?? EN[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? `{${name}}`);
}

export function getLocale() { return locale; }

export function setLocale(nextLocale, { notify = true } = {}) {
  locale = SUPPORTED.has(nextLocale) ? nextLocale : 'en';
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = locale;
    document.documentElement.dataset.locale = locale;
    applyStaticTranslations();
  }
  if (notify && typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
    window.dispatchEvent(new CustomEvent('overlogic:localechange', { detail: { locale } }));
  }
}

export function applyStaticTranslations(root = document) {
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  }
  for (const element of root.querySelectorAll('[data-i18n-title]')) {
    element.setAttribute('title', t(element.dataset.i18nTitle));
  }
  for (const element of root.querySelectorAll('[data-i18n-aria-label]')) {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  }
}

export function entity(kind, id, fallback = '', field = 'name') {
  if (locale === 'en') return fallback || id;
  const entry = ENTITIES[locale]?.[kind]?.[id];
  if (!entry) return fallback || id;
  return field === 'description' ? (entry[1] || fallback || '') : (entry[0] || fallback || id);
}

export function localizedSearchText(kind, id, fallbackName, fallbackDescription) {
  return `${entity(kind, id, fallbackName)} ${entity(kind, id, fallbackDescription, 'description')} ${fallbackName} ${fallbackDescription}`.toLowerCase();
}

